const submitForm = async () => {

  if (submitting.value) {
    return;
  }

  submitting.value = true;

  try {

    const payload = {
      companyId: Number(form.companyId),

      category: form.category,

      machine: form.machine,

      projectType: form.projectType,

      capacity: form.capacity,

      product: form.product,

      automation: form.automation,

      budget: form.budget,

      message: form.message,

      name: form.name,

      businessName: form.businessName,

      email: form.email,

      phone: form.phone,

      city: form.city,

      state: form.state
    };


    console.log(
      "Submitting project enquiry:",
      payload
    );


    const response =
      await createProjectEnquiry(payload);


    console.log(
      "Enquiry saved successfully:",
      response.data
    );


    await Swal.fire({
      icon: "success",
      title: "Enquiry Submitted!",
      text: "Thank you for contacting RBM Engineers. Our engineering team will review your requirement and contact you shortly.",
      confirmButtonText: "Done",
      confirmButtonColor: "#1b5e8c"
    });


    Object.keys(form).forEach(key => {
      form[key] = "";
    });


  } catch (error) {

    await Swal.fire({
      icon: "error",
      title: "Submission Failed",
      text: "Unable to submit your enquiry. Please try again.",
      confirmButtonText: "Try Again",
      confirmButtonColor: "#1b5e8c"
    });


    if (error.response) {

      console.error(
        "Backend response:",
        error.response.data
      );

      alert(
